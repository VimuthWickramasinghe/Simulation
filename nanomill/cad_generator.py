    def generate_pure_stl_mesh(self) -> bytes:
        """
        Generates a valid binary STL mesh directly in pure Python with exact gear sizing,
        coplanar gear heights, cooling fins, and indicators.
        """
        R_sun = self.geom.sun_radius_m * 1000.0
        r_vial = self.geom.vial_radius_m * 1000.0
        h_vial = self.geom.vial_height_m * 1000.0
        n_vials = self.geom.num_vials
        k_abs = abs(self.kin.gear_ratio_k)

        # Exact gear kinematics
        z_planet = 20
        z_sun = int(round(k_abs * z_planet))
        r_planet_pitch = R_sun * (z_planet / (z_sun + z_planet))
        r_sun_pitch = R_sun * (z_sun / (z_sun + z_planet))

        gear_z = 0.0
        gear_h = 16.0
        disc_z = gear_z + gear_h + 4.0
        disc_h = 18.0
        vial_base_z = disc_z + disc_h
        disc_r = R_sun + r_vial + 30.0

        triangles = []

        def add_cylinder(cx, cy, cz, r, h, segments=24):
            theta = np.linspace(0, 2 * np.pi, segments, endpoint=False)
            top_z = cz + h
            bot_z = cz
            for i in range(segments):
                i_next = (i + 1) % segments
                x1, y1 = cx + r * np.cos(theta[i]), cy + r * np.sin(theta[i])
                x2, y2 = cx + r * np.cos(theta[i_next]), cy + r * np.sin(theta[i_next])

                triangles.append(((x1, y1, bot_z), (x2, y2, bot_z), (x2, y2, top_z)))
                triangles.append(((x1, y1, bot_z), (x2, y2, top_z), (x1, y1, top_z)))
                triangles.append(((cx, cy, top_z), (x1, y1, top_z), (x2, y2, top_z)))
                triangles.append(((cx, cy, bot_z), (x2, y2, bot_z), (x1, y1, bot_z)))

        def add_box(cx, cy, cz, dx, dy, dz):
            x0, x1 = cx - dx / 2, cx + dx / 2
            y0, y1 = cy - dy / 2, cy + dy / 2
            z0, z1 = cz, cz + dz
            faces = [
                ((x0, y0, z0), (x1, y0, z0), (x1, y1, z0), (x0, y1, z0)),
                ((x0, y0, z1), (x1, y0, z1), (x1, y1, z1), (x0, y1, z1)),
                ((x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1)),
                ((x0, y1, z0), (x1, y1, z0), (x1, y1, z1), (x0, y1, z1)),
                ((x0, y0, z0), (x0, y1, z0), (x0, y1, z1), (x0, y0, z1)),
                ((x1, y0, z0), (x1, y1, z0), (x1, y1, z1), (x1, y0, z1)),
            ]
            for p0, p1, p2, p3 in faces:
                triangles.append((p0, p1, p2))
                triangles.append((p0, p2, p3))

        # 1. Base Housing
        add_cylinder(0, 0, -22.0, disc_r + 15.0, 22.0, segments=36)

        # 2. Central Sun Gear (Coplanar with planet gears at gear_z)
        add_cylinder(0, 0, gear_z, r_sun_pitch, gear_h, segments=36)

        # 3. Sun Carrier Disc (Sits above gears)
        add_cylinder(0, 0, disc_z, disc_r, disc_h, segments=36)

        # 4. Planetary Vials, Planet Gears, and Cooling Fins
        for v in range(n_vials):
            angle = v * (2.0 * np.pi / n_vials)
            vx = R_sun * np.cos(angle)
            vy = R_sun * np.sin(angle)

            # Planet Gear at exact coplanar gear_z
            add_cylinder(vx, vy, gear_z, r_planet_pitch, gear_h, segments=24)

            # Spindle shaft connecting gear to vial
            add_cylinder(vx, vy, gear_z, 7.0, vial_base_z - gear_z, segments=16)

            # Vial cylinder sitting on carrier disc
            add_cylinder(vx, vy, vial_base_z, r_vial + 10.0, h_vial + 15.0, segments=24)

            # Annular Cooling Fins (5 rings)
            for f in range(5):
                fin_z = vial_base_z + 18.0 + f * 14.0
                add_cylinder(vx, vy, fin_z, r_vial + 18.0, 3.0, segments=24)

            # Vial clamp lid
            lid_z = vial_base_z + h_vial + 15.0
            add_cylinder(vx, vy, lid_z, r_vial + 13.0, 14.0, segments=24)

            # Indicator pointer bar on top of jar
            add_box(vx, vy, lid_z + 14.0, (r_vial + 10.0) * 1.5, 6.0, 4.0)

        # 5. Central Motor Shaft & Indicator
        add_cylinder(0, 0, disc_z, 14.0, 40.0, segments=20)
        add_box(0, 0, disc_z + 40.0, 34.0, 8.0, 4.0)

        # Build binary STL
        header = b"NanoMill Planetary Ball Mill (Exact Gear Meshing & Fins)".ljust(80, b"\0")
        num_tris = len(triangles)
        record_list = [header, np.uint32(num_tris).tobytes()]

        for tri in triangles:
            p1, p2, p3 = np.array(tri[0]), np.array(tri[1]), np.array(tri[2])
            normal = np.cross(p2 - p1, p3 - p1)
            norm_mag = np.linalg.norm(normal)
            normal = normal / norm_mag if norm_mag > 1e-6 else np.array([0.0, 0.0, 1.0])

            record = np.array(
                [
                    normal[0], normal[1], normal[2],
                    p1[0], p1[1], p1[2],
                    p2[0], p2[1], p2[2],
                    p3[0], p3[1], p3[2],
                ],
                dtype=np.float32,
            ).tobytes() + b"\0\0"
            record_list.append(record)

        return b"".join(record_list)

    def export_stl_file(self, filepath: str) -> str:
        """Saves binary STL file to disk."""
        data = self.generate_pure_stl_mesh()
        os.makedirs(os.path.dirname(os.path.abspath(filepath)), exist_ok=True)
        with open(filepath, "wb") as f:
            f.write(data)
        return filepath

